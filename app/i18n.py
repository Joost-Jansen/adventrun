def format_range(d1: date, d2: date, lang: str) -> str:
    """'1–7 december'; across months '28 november – 4 december'."""
    if d1.month == d2.month:
        return f"{d1.day}–{d2.day} {MONTHS[lang][d1.month - 1]}"
    return f"{format_date(d1, lang)} – {format_date(d2, lang)}"


class _KeepMissing(dict):
    """Leaves unknown placeholders as they are, for texts the browser fills in (the live summary)."""

    def __missing__(self, key: str) -> str:
        return "{" + key + "}"


def translator(lang: str, owner: str, charity: str):
    texts = T[lang]

    def t(key: str, **kw) -> str:
        return texts[key].format_map(_KeepMissing(owner=owner, charity=charity, **kw))

    return t
